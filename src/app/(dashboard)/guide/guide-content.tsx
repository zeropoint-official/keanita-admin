export function GuideContent() {
  const [q, setQ] = useState('');
  const visible = useMemo(() => {
    const t = q.trim().toLowerCase();
    if (!t) return SECTIONS;
    return SECTIONS.filter((s) => (s.title + ' ' + s.keywords).toLowerCase().includes(t));
  }, [q]);

  return (
    <div className="grid gap-6 lg:grid-cols-[230px_1fr] items-start">
      <div className="lg:sticky lg:top-6 space-y-3">
        <Input placeholder="Αναζήτηση στον οδηγό…" value={q} onChange={(e) => setQ(e.target.value)} />
        <nav className="space-y-0.5">
          {visible.map((s) => (
            <a key={s.id} href={`#${s.id}`} className="flex items-center gap-2 rounded-md px-2 py-1.5 text-sm text-muted-foreground hover:bg-muted hover:text-foreground">
              <s.icon className="h-4 w-4 shrink-0" />{s.title}
            </a>
          ))}
          {visible.length === 0 && <p className="px-2 py-1.5 text-sm text-muted-foreground">Δεν βρέθηκε κάτι.</p>}
        </nav>
      </div>
      <div className="space-y-6 min-w-0">
        {visible.map((s) => (
          <Card key={s.id} id={s.id} className="scroll-mt-6">
            <CardHeader>
              <CardTitle className="flex items-center gap-2"><s.icon className="h-5 w-5 text-[#E60C10]" />{s.title}</CardTitle>
              {s.id === 'sponsors' && <CardDescription className="flex items-center gap-1.5"><Badge variant="secondary">Διάβασέ το πριν στήσεις καμπάνια</Badge></CardDescription>}
            </CardHeader>
            <CardContent>{s.body}</CardContent>
          </Card>
        ))}
      </div>
    </div>
  );
}
